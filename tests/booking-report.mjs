import assert from 'node:assert/strict';
import {reportMonth,reportRows} from '../app/admin/reports/model.ts';
const rows=[{id:'a',start_at:'2026-12-31T18:00:00Z',status:'approved'},{id:'b',start_at:'2027-02-28T17:00:00Z',status:'cancelled'},{id:'c',start_at:'2027-02-28T16:59:00Z',status:'rejected'},{id:'d',start_at:'2026-12-31T16:59:00Z',status:'pending'}];
assert.equal(reportMonth(rows[0].start_at),'2027-01');
assert.deepEqual(reportRows(rows,'2027-01','2027-02').map(r=>r.id),['a','c']);
assert.deepEqual(reportRows(rows,'2027-03','2027-02'),[]);
assert.equal(rows[0].id,'a');
console.log('PASS: inclusive month range uses Bangkok timezone, year boundary, all statuses and preserves source');
import {reportSummary} from '../app/admin/reports/model.ts';
const sample=[{id:'a',venue_name:'A',start_at:'2026-01-31T18:00:00Z',status:'approved'},{id:'b',venue_name:'A',start_at:'2026-02-20T10:00:00Z',status:'pending'},{id:'c',venue_name:'B',start_at:'2026-03-01T00:00:00Z',status:'cancelled'}];
const summary=reportSummary(sample,['A','B','C'],'2026-01','2026-02');
assert.equal(summary.total,2);assert.deepEqual(summary.totals,[0,2]);
assert.deepEqual(summary.venues.find(v=>v.name==='A').counts,[0,2]);
assert.equal(summary.venues.find(v=>v.name==='C').total,0);
assert.equal(summary.venues.reduce((n,v)=>n+v.total,0),summary.total);
assert.equal(reportSummary([],['A'],'2026-01','2026-12').total,0);
console.log('PASS: monthly venue matrix and chart totals agree, include zero venues, respect month filter and Bangkok boundary');
