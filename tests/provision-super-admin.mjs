import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { provisionSuperAdmin, provisionInitialAdmin } from '../scripts/provision-super-admin.mjs';
import { scryptAsync } from '@noble/hashes/scrypt.js';
import { bytesToHex,hexToBytes } from '@noble/hashes/utils.js';
const password=randomUUID();
const calls=[];
const execute=async batch=>{calls.push(batch);return calls.length===1?[{results:[{n:0}]}]:[{meta:{changes:1}},{meta:{changes:1}}];};
assert.deepEqual(await provisionSuperAdmin({execute,username:'example-admin',password}),{created:true});
assert.equal(calls[1].length,2);
assert(calls[1][0].sql.includes('WHERE NOT EXISTS'));
assert(calls[1][1].sql.includes('WHERE changes()>0'));
const stored=calls[1][0].params[3];assert.notEqual(stored,password);
const [algorithm,n,r,p,salt,hash]=stored.split('$');assert.equal(algorithm,'scrypt');
const verify=await scryptAsync(password,hexToBytes(salt),{N:Number(n),r:Number(r),p:Number(p),dkLen:32,maxmem:64*1024*1024});
assert.equal(bytesToHex(verify),hash);
assert(!JSON.stringify(calls).includes(password));
let existingCalls=0;
assert.deepEqual(await provisionSuperAdmin({execute:async()=>{existingCalls++;return[{results:[{n:1}]}]},username:'example-admin',password}),{created:false});
assert.equal(existingCalls,1);
await assert.rejects(()=>provisionSuperAdmin({execute,username:'bad space',password}));
await assert.rejects(()=>provisionSuperAdmin({execute,username:'example-admin',password:'short'}));
console.log('PASS: initial Super admin provisioning, password compatibility, no plaintext password in SQL/audit, and no reset of existing accounts.');

const adminCalls=[];const adminExecute=async batch=>{adminCalls.push(batch);return adminCalls.length===1?[{results:[{n:0}]}]:adminCalls.length===2?[{results:[{id:'existing-owner'}]}]:[{meta:{changes:1}},{meta:{changes:1}}]};
assert.deepEqual(await provisionInitialAdmin({execute:adminExecute,username:'example.admin@example.com',password:'abcdef'}),{created:true});
assert(adminCalls[2][0].sql.includes("'admin'"));assert(adminCalls[2][0].sql.includes('bootstrap'));
const adminStored=adminCalls[2][0].params[3];const [a,an,ar,ap,as,ah]=adminStored.split('$');
const av=await scryptAsync('abcdef',hexToBytes(as),{N:Number(an),r:Number(ar),p:Number(ap),dkLen:32,maxmem:64*1024*1024});assert.equal(bytesToHex(av),ah);
assert(!JSON.stringify(adminCalls).includes('abcdef'));
let skipped=0;assert.deepEqual(await provisionInitialAdmin({execute:async()=>{skipped++;return[{results:[{n:1}]}]},username:'example.admin@example.com',password:'abcdef'}),{created:false});assert.equal(skipped,1);
console.log('PASS: email Admin with six-character password and preservation after later account edits.');
